package tunnel

import (
	"context"
	"encoding/json"
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"sync"
	"time"
)

// Cloudflare runs cloudflared: a named tunnel on your own hostname (stable
// URL, needs a Cloudflare account and a zone), or without a hostname a
// quick tunnel (random trycloudflare.com URL, no account, changes on every
// restart: for trying things out).
type Cloudflare struct {
	o   Options
	bin string
	id  string
	cfg string
}

func (c *Cloudflare) Name() string { return "cloudflare" }

func (c *Cloudflare) Prepare(ctx context.Context, local string) (string, error) {
	bin, err := lookPath("cloudflared", "/opt/homebrew/bin/cloudflared", "/usr/local/bin/cloudflared")
	if err != nil {
		return "", &Error{Msg: "cloudflared is not installed",
			Fix: "install it: brew install cloudflared (macOS), or see https://developers.cloudflare.com/cloudflare-one/connections/connect-networks/downloads/"}
	}
	c.bin = bin
	if c.o.Hostname == "" {
		return "", nil // quick tunnel: the URL is printed when it starts
	}
	home, _ := os.UserHomeDir()
	if _, err := os.Stat(filepath.Join(home, ".cloudflared", "cert.pem")); err != nil {
		return "", &Error{Msg: "cloudflared is not logged in to your Cloudflare account",
			Fix: "run: cloudflared tunnel login   (choose the zone of " + c.o.Hostname + ")"}
	}
	id, err := c.tunnelID(ctx)
	if err != nil {
		return "", err
	}
	if id == "" {
		c.o.Log.Info("creating Cloudflare tunnel", "name", c.o.Name)
		if _, err := run(ctx, bin, "tunnel", "create", c.o.Name); err != nil {
			return "", err
		}
		if id, err = c.tunnelID(ctx); err != nil || id == "" {
			return "", fmt.Errorf("tunnel %s was created but cannot be found: %v", c.o.Name, err)
		}
	}
	creds := filepath.Join(home, ".cloudflared", id+".json")
	if _, err := os.Stat(creds); err != nil {
		return "", &Error{Msg: fmt.Sprintf("tunnel %q exists but its credentials (%s) are not on this machine", c.o.Name, creds),
			Fix: "use another --tunnel-name, or copy that file from the machine that created the tunnel"}
	}
	if _, err := run(ctx, bin, "tunnel", "route", "dns", "--overwrite-dns", c.o.Name, c.o.Hostname); err != nil {
		return "", err
	}
	c.id = id
	c.cfg = filepath.Join(c.o.StateDir, "cloudflared.yml")
	if err := os.MkdirAll(c.o.StateDir, 0o700); err != nil {
		return "", err
	}
	if err := os.WriteFile(c.cfg, []byte(cloudflaredConfig(id, creds, c.o.Hostname, local)), 0o600); err != nil {
		return "", err
	}
	return "https://" + c.o.Hostname, nil
}

func (c *Cloudflare) tunnelID(ctx context.Context) (string, error) {
	out, err := run(ctx, c.bin, "tunnel", "list", "--output", "json", "--name", c.o.Name)
	if err != nil {
		return "", err
	}
	return tunnelIDFromList(out, c.o.Name)
}

func (c *Cloudflare) Run(ctx context.Context, local string, onURL func(string)) error {
	if c.o.Hostname != "" {
		return supervise(ctx, c.o.Log, c.bin, []string{"tunnel", "--no-autoupdate", "--config", c.cfg, "run", c.id}, nil)
	}
	var (
		mu   sync.Mutex
		last string
	)
	return supervise(ctx, c.o.Log, c.bin, []string{"tunnel", "--no-autoupdate", "--url", local}, func(line string) {
		u := quickTunnelURL(line)
		if u == "" {
			return
		}
		mu.Lock()
		changed := u != last
		last = u
		mu.Unlock()
		if changed {
			c.o.Log.Info("quick tunnel is up (this URL changes whenever the tunnel restarts)", "url", u)
			onURL(u)
		}
	})
}

var quickURL = regexp.MustCompile(`https://[a-z0-9-]+\.trycloudflare\.com`)

func quickTunnelURL(line string) string {
	u := quickURL.FindString(line)
	if u == "https://api.trycloudflare.com" {
		return ""
	}
	return u
}

func tunnelIDFromList(out, name string) (string, error) {
	var list []struct {
		ID        string    `json:"id"`
		Name      string    `json:"name"`
		DeletedAt time.Time `json:"deleted_at"`
	}
	if err := json.Unmarshal([]byte(strings.TrimSpace(out)), &list); err != nil {
		return "", fmt.Errorf("cannot read `cloudflared tunnel list`: %v", err)
	}
	for _, t := range list {
		if t.Name == name && t.DeletedAt.IsZero() {
			return t.ID, nil
		}
	}
	return "", nil
}

func cloudflaredConfig(id, creds, hostname, local string) string {
	if u, err := url.Parse(local); err == nil && u.Host != "" {
		local = u.Scheme + "://" + u.Host
	}
	return fmt.Sprintf(`# Generated by myco hub up; edits are overwritten.
tunnel: %s
credentials-file: %s
ingress:
  - hostname: %s
    service: %s
  - service: http_status:404
`, id, creds, hostname, local)
}
