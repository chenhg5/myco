package api

import (
	"encoding/json"
	"time"
)

// BrowserComponentStatus describes an optional local desktop component, not a
// Hub action provider. Protocol 1 deliberately advertises no agent actions.
type BrowserComponentStatus struct {
	Protocol        int    `json:"protocol"`
	Version         string `json:"version"`
	Installed       bool   `json:"installed"`
	Supported       bool   `json:"supported"`
	Running         bool   `json:"running"`
	UpdateAvailable bool   `json:"update_available,omitempty"`
	Reason          string `json:"reason,omitempty"`
	DownloadBytes   int64  `json:"download_bytes,omitempty"`
}
type BrowserProfile struct {
	ID      string `json:"id"`
	Name    string `json:"name"`
	Running bool   `json:"running"`
	Agents  bool   `json:"agents"`
}
type BrowserStatus struct {
	Protocol  int              `json:"protocol"`
	Version   string           `json:"version"`
	Installed bool             `json:"installed"`
	Supported bool             `json:"supported"`
	Reason    string           `json:"reason,omitempty"`
	Browsers  []string         `json:"browsers"`
	Machine   string           `json:"machine"`
	Profiles  []BrowserProfile `json:"profiles"`
}

// BrowserApprovalRequest contains the script and child snapshots a page asks
// its local owner to review. Workspace, account and page come from the native
// bridge context; a request alone never approves execution.
type BrowserApprovalRequest struct {
	ScriptID string                     `json:"script_id"`
	Version  int64                      `json:"version"`
	Profile  string                     `json:"profile"`
	Script   json.RawMessage            `json:"script"`
	Scripts  map[string]json.RawMessage `json:"scripts,omitempty"`
}
type BrowserApproval struct {
	ScriptID   string    `json:"script_id"`
	Version    int64     `json:"version"`
	Digest     string    `json:"digest"`
	Profile    string    `json:"profile"`
	ApprovedAt time.Time `json:"approved_at"`
	Name       string    `json:"name"`
}
type BrowserReviewedCode struct {
	Script string `json:"script"`
	Node   string `json:"node"`
	Type   string `json:"type"`
	Code   string `json:"code"`
}

// BrowserApprovalReview is generated by the native backend for its trusted
// confirmation UI. The child cannot supply its summary or obtain its nonce.
type BrowserApprovalReview struct {
	ScriptID    string                     `json:"script_id"`
	Version     int64                      `json:"version"`
	Profile     string                     `json:"profile"`
	ProfileName string                     `json:"profile_name"`
	Name        string                     `json:"name"`
	Digest      string                     `json:"digest"`
	URLs        []string                   `json:"urls"`
	Code        []BrowserReviewedCode      `json:"code"`
	Children    []string                   `json:"children"`
	Script      json.RawMessage            `json:"script"`
	Scripts     map[string]json.RawMessage `json:"scripts"`
}
