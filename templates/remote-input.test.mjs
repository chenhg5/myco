import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source=fs.readFileSync(new URL('./src/_lib/remote-input.ts',import.meta.url),'utf8');
const {outputText}=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}});
const {Touchpad,textInput}=await import('data:text/javascript;base64,'+Buffer.from(outputText).toString('base64'));
assert.deepEqual(textInput('你好🙂',true),[{kind:'text',text:'你好🙂'}]);
assert.equal(textInput('你好',false),null);
assert.equal(textInput('abc\0',true),null);
assert.equal(textInput('中'.repeat(257),true),null);
assert.equal(textInput('a'.repeat(33),false),null);
assert.deepEqual(textInput('A!\n',false).filter(x=>x.kind==='key'&&x.down).map(x=>x.code),['ShiftLeft','KeyA','ShiftLeft','Digit1','Enter']);
assert.deepEqual(textInput('一\r\n二\t',true),[{kind:'text',text:'一'},{kind:'key',code:'Enter',down:true},{kind:'key',code:'Enter',down:false},{kind:'text',text:'二'},{kind:'key',code:'Tab',down:true},{kind:'key',code:'Tab',down:false}]);
const out=[],pad=new Touchpad(e=>out.push(e));
pad.down(1,10,10,1000);pad.move(1,60,35,100,100);pad.up(1,1100);
assert.deepEqual(pad.point,{x:1,y:.75});assert.equal(out.filter(x=>x.kind==='button').length,0,'moving a finger must not click or drag');
pad.down(1,10,10,2000);pad.up(1,2050);assert.equal(out.filter(x=>x.kind==='button').length,2);
pad.down(1,10,10,2200);pad.up(1,2250);assert.equal(out.at(-1).clicks,2);
const before=out.length;pad.down(1,20,20,3000);pad.down(2,40,20,3000);pad.move(1,20,40,100,100);pad.up(1,3100);pad.up(2,3100);
assert.deepEqual(out.slice(before),[{kind:'scroll',delta:-20}]);
pad.drag(true);assert.equal(out.at(-1).down,true);pad.reset();assert.deepEqual(out.at(-1),{kind:'release'});assert.equal(pad.dragging,false);
console.log('PASS touchpad gestures, drag release, legacy physical keys, Unicode and composition text planning');

const viewport=fs.readFileSync(new URL('./src/_lib/remote-viewport.ts',import.meta.url),'utf8');
const compiled=ts.transpileModule(viewport,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {zoomView,pinchView,boundedView,followPointer}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
const initial={scale:1,x:0,y:0};
assert.deepEqual(zoomView(initial,2,{x:100,y:50},200,100),{scale:2,x:-100,y:-50});
assert.deepEqual(pinchView(initial,2,{x:100,y:50},{x:110,y:55},200,100),{scale:2,x:-90,y:-45});
assert.deepEqual(boundedView({scale:9,x:-9999,y:9999},200,100),{scale:5,x:-800,y:0});
assert.deepEqual(zoomView({scale:2,x:-100,y:-50},1,{x:100,y:50},200,100),initial);
const followed=followPointer({scale:2,x:-100,y:-50},{x:0,y:0},200,100);
assert.equal(followed.x,0);assert.equal(followed.y,0);
console.log('PASS anchored zoom, pinch pan, bounds, reset and pointer visibility');
