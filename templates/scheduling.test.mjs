// Time zones, DST, overlapping buffers, horizon/notice and calendar exports.
import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
const source = fs.readFileSync(new URL("src/scheduling/engine.ts", import.meta.url), "utf8");
const e = await import("data:text/javascript;base64," + Buffer.from(ts.transpile(source, { target: 99, module: 99 })).toString("base64"));
const event = { ...e.defaultEvent, title: "Consultation", notice: 0, horizon: 30 };
const schedule = { week: structuredClone(e.defaultWeek), overrides: [] };
const now = Date.parse("2026-11-22T00:00:00Z");
const slots = (date, zone = "Asia/Shanghai", bookings = [], ev = event, s = schedule) => e.slotsForDay(date, zone, "Asia/Shanghai", ev, s, bookings, now);
assert.equal(e.validSchedule(schedule), true);
assert.equal(e.validSchedule({}), false);
assert.equal(e.validRanges([{ start: "09:00", end: "10:00" }, { start: "09:45", end: "11:00" }]), false);
assert.equal(e.validRanges([{ start: "12:00", end: "11:00" }]), false);
assert.equal(e.validRanges([{ start: "24:00", end: "25:00" }]), false);
assert.equal(e.validRanges([null]), false);
assert.equal(e.validEvent({ ...event, duration: 17 }), false);
assert.equal(e.validEvent({ ...event, before: -1 }), false);
assert.equal(e.validDate("2026-02-30"), false);
assert.equal(e.validDate("2028-02-29"), true);
assert.equal(slots("2026-11-22").length, 0, "Sunday is closed");
const monday = slots("2026-11-23");
assert.equal(monday[0].start, "2026-11-23T01:00:00.000Z");
assert.equal(monday.at(-1).end, "2026-11-23T09:00:00.000Z");
assert(monday.every(s => !(s.start >= "2026-11-23T04:00" && s.start < "2026-11-23T05:00")), "Lunch break is not bookable");
assert.equal(slots("2026-11-23", "Asia/Shanghai", [], event, { ...schedule, overrides: [{ date: "2026-11-23", ranges: [] }] }).length, 0);
assert.equal(slots("2026-11-22", "America/Los_Angeles").at(-1).day, "2026-11-23", "Visitor's previous date maps to host's Monday");
assert.equal(slots("2026-11-21").length, 0);
assert.equal(slots("2026-12-23").length, 0, "Horizon is bounded");
const b = { id: "b", type: "other", title: "Long meeting", start: "2026-11-23T02:00:00.000Z", end: "2026-11-23T03:00:00.000Z", before: 15, after: 15, status: "confirmed", name: "Ann", email: "ann@example.com", notes: "Hello\nBEGIN:VEVENT", location: "Studio, floor 2; east", zone: "UTC", created: "2026-11-22T00:00:00Z" };
assert.equal(e.validBooking(b), true);
assert.equal(e.validBooking({ ...b, before: -10 }), false);
assert.equal(e.validBooking({ ...b, start: "invalid date" }), false);
assert.equal(slots("2026-11-23", "Asia/Shanghai", [b]).some(s => s.start === "2026-11-23T01:30:00.000Z"), false, "Other types and their buffers block time");
assert.equal(slots("2026-11-23", "Asia/Shanghai", [b]).some(s => s.start === "2026-11-23T01:15:00.000Z"), true, "Half-open boundary may touch");
assert.equal(slots("2026-11-23", "Asia/Shanghai", [{ ...b, status: "cancelled" }]).length, monday.length);
assert.equal(slots("2026-11-23", "Asia/Shanghai", [], { ...event, before: 15 })[0].start, "2026-11-23T01:15:00.000Z", "Buffers stay within availability and ledger day");
assert.equal(slots("2026-11-23", "Asia/Shanghai", [], { ...event, enabled: false }).length, 0);
assert.equal(e.slotsForDay("2026-11-23", "UTC", "Asia/Shanghai", { ...event, notice: 60 }, schedule, [], Date.parse("2026-11-23T01:00:00Z"))[0].start, "2026-11-23T02:00:00.000Z");
assert.deepEqual(e.wallInstants("2026-03-08", 150, "America/New_York"), [], "DST spring gap");
assert.deepEqual(e.wallInstants("2026-11-01", 90, "America/New_York"), [Date.parse("2026-11-01T05:30Z"), Date.parse("2026-11-01T06:30Z")], "Both repeated times retained");
assert.deepEqual(e.wallInstants("2026-04-05", 105, "Australia/Lord_Howe"), [Date.parse("2026-04-04T14:45Z"), Date.parse("2026-04-04T15:15Z")], "Half-hour DST fold");
const dstSchedule = { week: Object.fromEntries(Array.from({ length: 7 }, (_, d) => [d, [{ start: "01:00", end: "04:00" }]])), overrides: [] };
const dstSlots = e.slotsForDay("2026-11-01", "America/New_York", "America/New_York", { ...event, duration: 60 }, dstSchedule, [], Date.parse("2026-10-31T00:00Z"));
assert(dstSlots.some(s => s.start === "2026-11-01T05:00:00.000Z"));
assert(dstSlots.some(s => s.start === "2026-11-01T06:00:00.000Z"));
assert(dstSlots.every(s => Date.parse(s.end) - Date.parse(s.start) === 3600000), "Duration stays elapsed time through DST");
const ics = e.calendarFile([{ ...b, id: "b\r\nBEGIN:VEVENT", title: "测试".repeat(80) }, { ...b, id: "c", status: "cancelled" }], "2026-11-22T00:00:00Z");
assert(ics.includes("DTSTART:20261123T020000Z\r\n"));
assert(ics.includes("STATUS:CANCELLED\r\n"));
assert(ics.includes("LOCATION:Studio\\, floor 2\\; east"));
assert(ics.includes("Hello\\nBEGIN:VEVENT"), "Guest text cannot inject ICS fields");
assert(ics.split("\r\n").every(line => Buffer.byteLength(line) <= 75));
assert.equal((ics.match(/\r\nBEGIN:VEVENT\r\n/g) || []).length, 2);
console.log("PASS scheduling: time zones/date line, DST gaps/folds, notice/horizon, buffers, overrides, cancellation and safe Unicode ICS");
